def finding(path, name, version, fixed, ecosystem, direct=None):
    return {"scanner": "sca", "tool": "trivy", "path": path,
            "package": {"ecosystem": ecosystem, "name": name, "version": version, "fixed_version": fixed, "direct": direct}}


class Scanned(unittest.TestCase):
    """A snapshot with the lockfiles and their manifests, annotated the way a scan does it."""

    def setUp(self):
        self.root = Path(tempfile.mkdtemp())
        self.write("pyproject.toml", PYPROJECT)
        self.write("poetry.lock", POETRY_LOCK)
        self.write("package.json", PACKAGE_JSON)
        self.write("package-lock.json", NPM_LOCK)

    def write(self, name, content):
        path = self.root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content if isinstance(content, str) else json.dumps(content), encoding="utf-8")
        return path

    def annotated(self, *findings):
        graphs = dependency_graph.graphs(TRIVY, lambda path: path.removeprefix("/src/"))
        dependency_graph.annotate(list(findings), graphs, declared_ranges.reader(self.root))
        return findings

    def fix(self, item, locale="en"):
        return localize(fix_guide.attach([item])[0]["fix"], locale)


class StarletteTests(Scanned):
    def test_the_declared_range_of_fastapi_is_read_and_the_simple_update_is_never_offered_alone(self):
        (starlette,) = self.annotated(finding("poetry.lock", "starlette", "0.37.2", "1.3.1", "PyPI"))
        self.assertEqual(starlette["package"]["introduced_by"], [{"name": "fastapi", "version": "0.110.1", "direct": "fastapi", "direct_version": "0.110.1",
                                                                "chain": ["fastapi"], "requires": ">=0.37.2,<0.38.0", "direct_requires": "^0.110.0"}])
        self.assertIs(starlette["package"]["direct"], False)
        fix = self.fix(starlette)
        self.assertEqual(fix["action"], "Update fastapi first, to a release that accepts starlette 1.3.1; then starlette.")
        self.assertEqual(fix["commands"], [
            {"label": "First, update fastapi", "action": "update", "code": "poetry add fastapi@latest"},
            {"label": "Then, update starlette", "action": "update", "code": "poetry update starlette"},
            {"label": "Check that it shows 1.3.1 or later", "action": "check", "code": "poetry show starlette"}])
        self.assertEqual(fix["steps"][:2], [
            "starlette 0.37.2 comes in through fastapi 0.110.1, which only accepts starlette >=0.37.2,<0.38.0. Updating starlette on its own "
            "can't take it to 1.3.1: fastapi has to move first.",
            "pyproject.toml declares fastapi as “^0.110.0”. The command below replaces that with its latest release: read fastapi's release "
            "notes and run your tests before merging."])
        self.assertIn("Reverify", fix["steps"][-1])  # and the scan confirms it
        es = self.fix(starlette, "es")
        self.assertEqual(es["action"], "Actualiza primero fastapi a una versión que acepte starlette 1.3.1; después, starlette.")
        self.assertEqual([command["label"] for command in es["commands"]], ["Primero, actualiza fastapi", "Después, actualiza starlette",
                                                                           "Comprueba que muestre 1.3.1 o superior"])

    def test_within_the_range_updating_the_package_is_enough(self):
        (starlette,) = self.annotated(finding("poetry.lock", "starlette", "0.37.2", "0.37.9", "PyPI"))
        fix = self.fix(starlette)
        self.assertNotIn("action", fix)
        self.assertEqual([command["code"] for command in fix["commands"]], ["poetry update starlette", "poetry show starlette"])
        self.assertTrue(fix["steps"][0].endswith("0.37.9 is within that range, so updating starlette is enough."))

    def test_a_direct_dependency_rewrites_its_own_declared_range(self):
        (fastapi,) = self.annotated(finding("poetry.lock", "fastapi", "0.110.1", "0.115.0", "PyPI"))
        fix = self.fix(fastapi)
        self.assertIs(fastapi["package"]["direct"], True)
        self.assertEqual([command["code"] for command in fix["commands"]], ['poetry add "fastapi>=0.115.0"', "poetry show fastapi"])


class NpmTests(Scanned):
    def test_a_parent_that_pins_it_moves_first_and_forcing_is_the_last_resort(self):
        (qs,) = self.annotated(finding("package-lock.json", "qs", "6.11.0", "6.11.1", "npm"))
        self.assertEqual([(entry["name"], entry.get("requires")) for entry in qs["package"]["introduced_by"]], [("express", "6.11.0"), ("body-parser", "6.11.0")])
        fix = self.fix(qs)
        self.assertEqual(fix["commands"], [{"label": "First, update express", "action": "update", "code": "npm install express@latest"},
                                           {"label": "Then, update qs", "action": "update", "code": "npm update qs"},
                                           {"label": "Check that it shows 6.11.1 or later", "action": "check", "code": "npm ls qs"}])
        self.assertEqual(fix["action"], "Update express first, to a release that accepts qs 6.11.1; then qs.")
        self.assertIsNone(fix["example"])  # no override up front: it would go against express's range
        self.assertIn("“overrides” in package.json", fix["steps"][-2])
        self.assertIn("package.json declares express as “^4.18.2”", fix["steps"][1])

    def test_a_parent_whose_range_allows_it_gets_npm_update(self):
        (minimist,) = self.annotated(finding("package-lock.json", "minimist", "1.2.5", "1.2.6", "npm"))
        fix = self.fix(minimist)
        self.assertEqual([command["code"] for command in fix["commands"]], ["npm update minimist", "npm ls minimist"])
        self.assertIn("which accepts minimist ^1.2.0", fix["steps"][0])

    def test_unknown_range_keeps_the_override_and_names_who_to_update(self):
        lock = json.loads(json.dumps(NPM_LOCK))
        del lock["packages"]["node_modules/markdown-it-qs"]["dependencies"]
        self.write("package-lock.json", lock)
        (minimist,) = self.annotated(finding("package-lock.json", "minimist", "1.2.5", "1.2.6", "npm"))
        fix = self.fix(minimist)
        self.assertEqual([command["code"] for command in fix["commands"]], ["npm install", "npm ls minimist"])
        self.assertEqual(fix["example"]["note"], "Better still: update markdown-it-qs, which brings it in.")


