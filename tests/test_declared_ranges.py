            ("npm", "^6.10.0", "6.11.1", True), ("npm", "6.11.0", "6.11.1", False), ("npm", "~6.11.0", "6.12.0", False),
            ("npm", "1.x", "1.9.9", True), ("npm", "1.2.3 - 2.3", "2.3.9", True), ("npm", "1.2.3 - 2.3", "2.4.0", False),
            ("npm", "<1.0.0 || >=2.0.0", "2.1.0", True), ("npm", "npm:^6.10.0", "6.11.1", True), ("npm", ">= 1.2 < 2", "1.5.0", True),
