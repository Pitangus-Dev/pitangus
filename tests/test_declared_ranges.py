        for path in ("linked/poetry.lock", f"../{outside.name}/poetry.lock", "broken/package-lock.json", "Cargo.lock", "missing/poetry.lock",
                     "loop/poetry.lock"):
            with self.subTest(path=path):
                self.assertIsNone(read(path))
        self.assertEqual(read("poetry.lock").of("FastAPI", "0.110.1", "Starlette"), ">=0.37.2,<0.38.0")  # Python names: any case


