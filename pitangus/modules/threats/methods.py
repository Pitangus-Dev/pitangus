def _identifier(value, used: set[str], problems: Problems, path: str, field) -> str | None:
    if not isinstance(value, str) or not ID.fullmatch(value) or value in used:
        problems.error(path, msg("threats.errors.unique_id", field=field), value if isinstance(value, str) else None)
        return None
    used.add(value)
    return value


def _list(payload: dict, key: str, limit: int, problems: Problems, too_many, prefix: str = "", identifier=None, at: str | None = None) -> list:
    raw = payload.get(key)
    if raw in (None, ""):
        return []
    where = at if at is not None else prefix + pointer(key)
    if not isinstance(raw, list):
        problems.error(where, msg("threats.problems.not_a_list", field=key), identifier)
        return []
    if len(raw) > limit:
        problems.error(where, too_many, identifier)
        return []
    return raw


def _element(value, elements: set[str], problems: Problems, path: str, identifier) -> str:
    if value in (None, ""):
        return ""
    if not isinstance(value, str) or value not in elements:
        problems.error(path, msg("threats.problems.dangling", field="element", value=str(value)[:40]), identifier)
        return ""
    return value


METHOD_ALIASES = {"attack_tree": "attack_trees", "mitre_attack": "attack", "mitre": "attack", "att&ck": "attack", "mitre_att&ck": "attack"}


def methodology_of(value, problems: Problems, path: str = "/methodology", top: Item | None = None) -> str:
    """The approach. One Pitangus doesn't have is modeled as Custom (free categories and sections) and its name is kept
    as a custom property of the model."""
    if value in (None, ""):
        return "stride"
    key = value.strip().lower().replace("-", "_").replace(" ", "_") if isinstance(value, str) else None
    key = METHOD_ALIASES.get(key or "", key)
    if key not in METHODOLOGIES:
        if not isinstance(value, str):
            problems.error(path, msg("threats.problems.not_text", field="methodology"))
            return "stride"
        problems.warning(path, msg("threats.problems.unknown_method", value=value[:40], allowed=", ".join(METHODOLOGIES)))
        if top is not None:
            top.kept["methodology"] = value[:80]
        return "custom"
    return key


# Each template's own vocabulary: a STRIDE model has STRIDE's six categories, a LINDDUN one LINDDUN's seven.
CATEGORY_KEYS = {"stride": {code: f"threats.stride.{code.lower()}" for code in ("S", "T", "R", "I", "D", "E")},
                 "linddun": {code: f"threats.linddun.{code.lower()}" for code in LINDDUN}}
CATEGORY_NAMES = {"stride": {"S": "Spoofing", "T": "Tampering", "R": "Repudiation", "I": "Information disclosure", "D": "Denial of service",
                             "E": "Elevation of privilege"},
                  "linddun": {"L": "Linking", "I": "Identifying", "Nr": "Non-repudiation", "D": "Detecting", "Dd": "Data disclosure",
                              "U": "Unawareness", "Nc": "Non-compliance"}}


def _category(item: Item, method: str, problems: Problems, identifier) -> str:
    """A team threat's category: free text, except in STRIDE and LINDDUN, whose categories are the method's own. There
    a code or a category's name (English or Spanish) is read as its code; anything else is kept as a custom property."""
    value = problems.text(item.get("category"), 40, item.at("category"), msg("threats.fields.category"), identifier=identifier)
    if not value or method not in CATEGORY_KEYS:
        return value
    for code, key in CATEGORY_KEYS[method].items():
        names = {code.lower(), CATEGORY_NAMES[method][code].lower(), *(t(key, locale).lower() for locale in ("en", "es"))}
        if value.lower() in names or value.lower().replace("-", " ") in names:
            if value != code:
                problems.info(item.at("category"), msg("threats.problems.value_alias", field="category", value=value, used=code), identifier)
            return code
    item.kept.setdefault("category", value)
    problems.warning(item.at("category"), msg("threats.problems.not_a_method_category", method=METHODOLOGIES[method], value=value,
                                              allowed=", ".join(CATEGORY_KEYS[method])), identifier)
    return ""


def _gate(step: Item, problems: Problems, identifier) -> str:
    """AND or OR: that is what an attack tree is made of. Another gate is kept as a custom property; the step is OR."""
    value = step.get("gate")
    if value in (None, ""):
        return "or"
    if not isinstance(value, str):
        problems.error(step.at("gate"), msg("threats.problems.not_text", field="gate"), identifier)
        return "or"
    key = normal(value)
    key = GATE_ALIASES.get(key, GATE_ALIASES.get(value.strip(), key))
    if key in ("and", "or"):
        if normal(value) != key:
            problems.info(step.at("gate"), msg("threats.problems.value_alias", field="gate", value=value[:40], used=key), identifier)
        return key
    step.kept.setdefault("gate", value[:40])
    problems.warning(step.at("gate"), msg("threats.problems.not_a_gate", value=value[:40]), identifier)
    return "or"


def equivalents(raw, problems: Problems, path: str) -> dict:
    """Where the team's own levels sort among ours: {"severity": {"Severe": "high"}}. A level without one goes after
    the known ones."""
    if raw in (None, "", {}):
        return {}
    if not isinstance(raw, dict):
        problems.error(path, msg("threats.errors.invalid_equivalents"))
        return {}
    result: dict = {}
    for field, scale in (("severity", SEVERITIES), ("likelihood", LEVELS), ("impact", LEVELS), ("difficulty", LEVELS)):
        mapping = raw.get(field)
        if mapping in (None, {}):
            continue
        if not isinstance(mapping, dict) or len(mapping) > 50:
            problems.error(path + pointer(field), msg("threats.errors.invalid_equivalents"))
            continue
        kept = {label[:40]: level for label, level in mapping.items() if isinstance(label, str) and label.strip() and level in scale}
        if len(kept) != len(mapping):
            problems.warning(path + pointer(field), msg("threats.problems.equivalents_ignored", field=field, allowed=", ".join(scale)))
        if kept:
            result[field] = kept
    for field in raw:
        if field not in ("severity", "likelihood", "impact", "difficulty"):
            problems.warning(path + pointer(field), msg("threats.problems.unknown_field", field=str(field)[:40]))
    return result


def technique_problem(key: str):
    """Why a well-formed technique ID can't be named, or None: revoked (and by what), deprecated, or not in ATT&CK."""
    state, replacement = attack.state(key)
    if state == "revoked":
        if replacement:
            return msg("threats.problems.technique_revoked", value=key, version=attack.version(), replacement=replacement,
                       name=attack.technique(replacement)[0])  # type: ignore[index]
        return msg("threats.problems.technique_revoked_alone", value=key, version=attack.version())
    if state == "deprecated":
        return msg("threats.problems.technique_deprecated", value=key, version=attack.version())
    if state == "unknown":
        return msg("threats.problems.technique_not_found", value=key, version=attack.version())
    return None


def validate(payload: dict, *, elements: set[str], problems: Problems, top: Item | None = None) -> dict:
    """What is specific to each approach. `elements`: ids of the model's components and flows, for the links. `top`:
    the model as read (the real path of each field, which may have come under a synonym, and its custom properties)."""
    at = top.at if top is not None else (lambda field: pointer(field))
    method = methodology_of(payload.get("methodology"), problems, at("methodology"), top)
    result: dict = {"methodology": method}
    modules = payload.get("custom_modules")
    if modules is None:
        # Custom is full freedom: without a list, the sections the model brings are its modules.
        modules = ["manual", "elements", *(module for module, section in (("trees", "attack_trees"), ("attack", "attack_mappings"), ("pasta", "pasta"))
                                           if method == "custom" and payload.get(section))]
    if not isinstance(modules, list):
        problems.error(at("custom_modules"), msg("threats.problems.not_a_list", field="custom_modules"))
        modules = ["manual", "elements"]
    kept = []
    for index, item in enumerate(modules):
        key = {"trees": "trees", "attack_trees": "trees", "mitre": "attack", "manual_threats": "manual"}.get(item, item) if isinstance(item, str) else item
        if isinstance(key, str) and key in CUSTOM_MODULES:
            kept.append(key)
        else:
            problems.warning(at("custom_modules") + pointer(index), msg("threats.problems.unknown_module", value=str(item)[:40], allowed=", ".join(sorted(CUSTOM_MODULES))))
    result["custom_modules"] = list(dict.fromkeys(kept))

    manual, used = [], set()
    for index, raw in enumerate(_list(payload, "manual_threats", LIMITS["manual_threats"], problems, msg("threats.errors.too_many_manual", limit=LIMITS["manual_threats"]),
                                      at=at("manual_threats"))):
        path = at("manual_threats") + pointer(index)
        if not isinstance(raw, dict):
            problems.error(path, msg("threats.errors.invalid_manual"))
            continue
        item = problems.read(raw, MANUAL_KEYS, path, raw.get("id"), aliases=MANUAL_ALIASES, merge=MANUAL_MERGE)
        identifier = _identifier(item.get("id"), used, problems, item.at("id"), msg("threats.fields.each_manual"))
        entry = {"id": identifier,
                 "title": problems.text(item.get("title"), 160, item.at("title"), msg("threats.fields.title"), required=True, identifier=identifier),
                 "category": _category(item, method, problems, identifier),
                 "element": _element(item.get("element"), elements, problems, item.at("element"), identifier),
                 "severity": problems.own_choice(item.get("severity"), SEVERITIES, item.at("severity"), "severity", identifier, aliases=SEVERITY_ALIASES) or "medium",
                 "scenario": problems.text(item.get("scenario"), 1500, item.at("scenario"), msg("threats.fields.scenario"), multiline=True, identifier=identifier),
                 "mitigation": problems.text(item.get("mitigation"), 1500, item.at("mitigation"), msg("threats.fields.mitigation"), multiline=True, identifier=identifier),
                 "likelihood": problems.own_choice(item.get("likelihood"), LEVELS, item.at("likelihood"), "likelihood", identifier, aliases=LEVEL_ALIASES),
                 "impact": problems.own_choice(item.get("impact"), LEVELS, item.at("impact"), "impact", identifier, aliases=LEVEL_ALIASES),
                 "owner": problems.text(item.get("owner"), 80, item.at("owner"), msg("threats.fields.owner"), identifier=identifier)}
        if identifier:
            manual.append(item.keep(entry))
    result["manual_threats"] = manual

    trees, tree_ids = [], set()
    for index, raw in enumerate(_list(payload, "attack_trees", LIMITS["attack_trees"], problems, msg("threats.errors.too_many_trees", limit=LIMITS["attack_trees"]),
                                      at=at("attack_trees"))):
        path = at("attack_trees") + pointer(index)
        if not isinstance(raw, dict):
            problems.error(path, msg("threats.errors.invalid_tree"))
            continue
        tree = problems.read(raw, TREE_KEYS, path, raw.get("id"), aliases=TREE_ALIASES, merge={"goal": ": "})
        tree_id = _identifier(tree.get("id"), tree_ids, problems, tree.at("id"), msg("threats.fields.each_tree"))
        nodes, node_ids, positions = [], set(), {}
        raw_nodes = _list(tree.values, "nodes", LIMITS["tree_nodes"], problems, msg("threats.errors.too_many_nodes", limit=LIMITS["tree_nodes"]), identifier=tree_id,
                          at=tree.at("nodes"))
        for position, node in enumerate(raw_nodes):
            node_path = tree.at("nodes") + pointer(position)
            if not isinstance(node, dict):
                problems.error(node_path, msg("threats.errors.invalid_node"), tree_id)
                continue
            step = problems.read(node, NODE_KEYS, node_path, node.get("id"), aliases=NODE_ALIASES, merge={"text": ": "})
            node_id = _identifier(step.get("id"), node_ids, problems, step.at("id"), msg("threats.fields.each_node"))
            element = _element(step.get("element"), elements, problems, step.at("element"), node_id)
            parent = step.get("parent") or None
            if parent is not None and not isinstance(parent, str):
                problems.error(step.at("parent"), msg("threats.problems.not_text", field="parent"), node_id)
                parent = None
            gate = _gate(step, problems, node_id)
            entry = {"id": node_id, "parent": parent,
                     "text": problems.text(step.get("text"), 200, step.at("text"), msg("threats.fields.step"), required=True, identifier=node_id),
                     "gate": gate, "element": element,
                     "difficulty": problems.own_choice(step.get("difficulty"), LEVELS, step.at("difficulty"), "difficulty", node_id, aliases=LEVEL_ALIASES),
                     "mitigated": problems.flag(step.get("mitigated"), step.at("mitigated"), "mitigated", node_id)}
            if node_id:
                nodes.append(step.keep(entry))
                positions[node_id] = step
        ids = {node["id"] for node in nodes}
        parents = {node["id"]: node["parent"] for node in nodes}
        broken = set()
        for node in nodes:
            if node["parent"] is not None and node["parent"] not in ids:
                problems.error(positions[node["id"]].at("parent"), msg("threats.problems.dangling", field="parent", value=node["parent"][:40]), node["id"])
                broken.add(node["id"])
        for node in nodes:
            seen, current = set(), node["id"]
            while current is not None and current not in broken:  # no cycles
                if current in seen:
                    problems.error(positions[node["id"]].at("parent"), msg("threats.errors.tree_cycle"), node["id"])
                    broken.add(node["id"])
                    break
                seen.add(current)
                current = parents.get(current)
        goal = problems.text(tree.get("goal"), 200, tree.at("goal"), msg("threats.fields.goal"), required=True, identifier=tree_id)
        if tree_id:
            trees.append(tree.keep({"id": tree_id, "goal": goal, "nodes": nodes}))
    result["attack_trees"] = trees

    mappings, seen_pairs = [], set()
    for index, raw in enumerate(_list(payload, "attack_mappings", LIMITS["attack_mappings"], problems, msg("threats.errors.too_many_mappings", limit=LIMITS["attack_mappings"]),
                                      at=at("attack_mappings"))):
        path = at("attack_mappings") + pointer(index)
        if isinstance(raw, str):  # a bare technique ID
            raw = {"technique": raw}
        if not isinstance(raw, dict):
            problems.error(path, msg("threats.problems.invalid_mapping"))
            continue
        technique = raw.get("technique") or raw.get("technique_id")
        mapping = problems.read(raw, MAPPING_KEYS, path, technique if isinstance(technique, str) else None, aliases=MAPPING_ALIASES, merge={"note": "\n\n"})
        technique = mapping.get("technique")
        key = technique.strip().upper() if isinstance(technique, str) else None
        if key is None or not TECHNIQUE_ID.fullmatch(key):
            problems.error(mapping.at("technique"), msg("threats.problems.technique_format", value=str(technique)[:40]))
            key = None
        elif (problem := technique_problem(key)) is not None:
            problems.warning(mapping.at("technique"), problem, key)
        element = _element(mapping.get("element"), elements, problems, mapping.at("element"), key)
        status = problems.own_choice(mapping.get("status"), MAPPING_STATUS, mapping.at("status"), "status", key, aliases=STATUS_ALIASES) or "relevant"
        note = problems.text(mapping.get("note"), 600, mapping.at("note"), msg("threats.fields.note"), multiline=True, identifier=key)
        if key is None:
            continue
        if (key, element) in seen_pairs:
            problems.warning(path, msg("threats.problems.duplicate_mapping", value=key), key)
            continue
        seen_pairs.add((key, element))
        mappings.append(mapping.keep({"technique": key, "element": element, "status": status, "note": note}))
    result["attack_mappings"] = mappings

    raw_pasta = payload.get("pasta") or {}
    if not isinstance(raw_pasta, dict):
        problems.error(at("pasta"), msg("threats.errors.invalid_pasta"))
        raw_pasta = {}
    stages = problems.read(raw_pasta, {key for key, _ in PASTA_STAGES}, at("pasta"), aliases=PASTA_ALIASES, merge=dict.fromkeys((key for key, _ in PASTA_STAGES), "\n\n"))
    if method == "pasta":  # PASTA has seven stages: another one is kept, but it isn't PASTA's
        for name in stages.kept:
            problems.escalate(at("pasta") + pointer(name), msg("threats.problems.not_a_pasta_stage", value=str(name)[:40]))
    pasta = {key: problems.text(stages.get(key), 4000, stages.at(key), msg("threats.fields.pasta_stage", stage=title), multiline=True)
             for key, title in PASTA_STAGES if stages.get(key)}
    result["pasta"] = {**pasta, **({KEPT: stages.kept} if stages.kept else {})}
    return result


def assumptions(raw, problems: Problems, path: str) -> list[dict]:
    """What the model takes for granted (the cloud provider's share, signed firmware…): [{id, text}]. A plain list of
    sentences is accepted too, each given an id."""
    if raw in (None, ""):
        return []
    if not isinstance(raw, list):
        problems.error(path, msg("threats.problems.not_a_list", field="assumptions"))
        return []
    if len(raw) > LIMITS["assumptions"]:
        problems.error(path, msg("threats.errors.too_many_assumptions", limit=LIMITS["assumptions"]))
        return []
    result, used = [], {item["id"] for item in raw if isinstance(item, dict) and isinstance(item.get("id"), str) and ID.fullmatch(item["id"])}
    taken: set[str] = set()
    for index, value in enumerate(raw):
        where = path + pointer(index)
        if isinstance(value, str):
            value = {"text": value}
        if not isinstance(value, dict):
            problems.error(where, msg("threats.errors.invalid_assumption"))
            continue
        item = problems.read(value, ASSUMPTION_KEYS, where, value.get("id"), aliases=ASSUMPTION_ALIASES, merge={"text": "\n\n"})
        identifier = item.get("id")
        if identifier in (None, ""):
            number = 1
            while f"a{number}" in used:
                number += 1
            identifier = f"a{number}"
            used.add(identifier)
        identifier = _identifier(identifier, taken, problems, item.at("id"), msg("threats.fields.each_assumption"))
        text = problems.text(item.get("text"), 1000, item.at("text"), msg("threats.fields.assumption"), required=True, multiline=True, identifier=identifier)
        if identifier and text:
            result.append(item.keep({"id": identifier, "text": text}))
    return result


def open_paths(tree: dict) -> int:
    """How many of the goal's paths an attacker can still take. An AND step is cut when one of its steps is mitigated;
    an OR step, only when all of them are. Same rule as the panel's tree editor."""
    children: dict = {}
    for node in tree.get("nodes") or []:
        children.setdefault(node.get("parent"), []).append(node)

    def blocked(node: dict) -> bool:
        kids = children.get(node["id"], [])
        if node.get("mitigated"):
            return True
        if not kids:
            return False
        return any(blocked(kid) for kid in kids) if node.get("gate") == "and" else all(blocked(kid) for kid in kids)
    return sum(1 for node in children.get(None, []) if not blocked(node))


def technique_label(key: str):
    """A technique's name for the reader: for the ones we suggest, MITRE's English name or its Spanish interpretation;
    for the rest of ATT&CK, the official name as published. A revoked, deprecated or unknown ID says so."""
    if key in TECHNIQUES:
        name, spanish, _ = TECHNIQUES[key]
        return inline({"en": name, "es": spanish})
    entry = attack.technique(key)
    if entry:
        return entry[0]
    state, replacement = attack.state(key)
    if state == "revoked":
        return msg("threats.attack.revoked_label", replacement=replacement) if replacement else msg("threats.attack.revoked_alone")
    if state == "deprecated":
        return msg("threats.attack.deprecated_label", name=attack.data()["deprecated"][key])
    return msg("threats.attack.not_found", version=attack.version())


def technique_tactics(key: str) -> list[str]:
    entry = attack.technique(key) or attack.technique(key.split(".")[0])
    return list(entry[1]) if entry else []


def catalog() -> dict:
    """What the panel needs for each approach; the usage guides live in the panel. `techniques`: the ones we suggest,
    with a Spanish interpretation; `attack`: all of ATT&CK, to recognize and name any ID."""
    full = attack.data()
    return {"methodologies": METHODOLOGIES, "linddun": LINDDUN, "tactics": TACTICS,
            "techniques": {key: {"name": name, "label": technique_label(key), "name_es": technique_label(key), "tactics": tactics}
                           for key, (name, _, tactics) in TECHNIQUES.items()},
            "attack": {"version": full["version"], "techniques": full["techniques"], "revoked": full["revoked"], "deprecated": full["deprecated"]},
            "suggestions": SUGGESTIONS, "pasta_stages": [{"key": key, "title": title} for key, title in PASTA_STAGES]}
